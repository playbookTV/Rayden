import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const root = new URL("../", import.meta.url);
const source = ts.createSourceFile(
  "icons.ts",
  readFileSync(new URL("src/components/Icon/icons.ts", root), "utf8"),
  ts.ScriptTarget.Latest,
  true
);
const declarations = source.statements
  .filter(ts.isVariableStatement)
  .flatMap((node) => [...node.declarationList.declarations]);
const registry = declarations.find((node) => node.name.getText(source) === "icons")?.initializer;
assert.ok(
  registry && ts.isObjectLiteralExpression(registry),
  "Expected the canonical icons registry"
);
const entries = registry.properties
  .map((property) => {
    assert.ok(ts.isPropertyAssignment(property) && ts.isIdentifier(property.initializer));
    const name = ts.isStringLiteral(property.name)
      ? property.name.text
      : property.name.getText(source);
    const exportName = property.initializer.text;
    const record = declarations.find(
      (node) => node.name.getText(source) === exportName
    )?.initializer;
    assert.ok(record && ts.isObjectLiteralExpression(record), `Missing data for ${name}`);
    assert.deepEqual(record.properties.map((node) => node.name.getText(source)).sort(), [
      "outline",
      "solid",
    ]);
    return { name, exportName };
  })
  .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
assert.equal(
  new Set(entries.map((entry) => entry.name)).size,
  entries.length,
  "Duplicate icon names"
);
const json = JSON.stringify(entries, null, 2);
const typescript = `// Generated by scripts/generate-icon-catalog.mjs. Do not edit by hand.\nimport type { IconName } from "./icons";\n\n/** Exact registry names and static data exports; contains no SVG artwork. */\nexport const iconCatalog = ${json} as const satisfies readonly { name: IconName; exportName: string }[];\n\n/** Registry names, suitable for search and autocomplete. */\nexport const iconNames: readonly IconName[] = /* @__PURE__ */ iconCatalog.map((entry) => entry.name);\n`;
for (const [path, content] of [
  ["src/components/Icon/catalog.ts", typescript],
  ["packages/rayden-ai/src/manifests/icons.generated.json", json + "\n"],
]) {
  const destination = new URL(path, root);
  if (process.argv.includes("--check")) {
    assert.equal(
      readFileSync(destination, "utf8"),
      content,
      `${path} is stale; run pnpm icons:build`
    );
  } else writeFileSync(destination, content);
}
console.log(`${entries.length} icon names and exports verified in ${fileURLToPath(root)}`);
